//! Exercise the production SharedChannel in both cross-language directions.
use nostr::JsonUtil;
use nostr_double_ratchet::{Result, SharedChannel};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::{fs, path::PathBuf};

#[derive(Serialize, Deserialize)]
struct Vectors {
    description: String,
    secret_hex: String,
    channel_pubkey: String,
    encrypted_event: Value,
    plaintext_rumor: Value,
    group_tagged_event: Value,
}

fn directory() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(3)
        .unwrap()
        .join("test-vectors")
}

#[test]
#[ignore = "writes an interop fixture; run the explicit vector-generation lane"]
fn generate_rust_shared_channel_vectors() -> Result<()> {
    let secret = [0x27; 32];
    let channel = SharedChannel::new(&secret)?;
    let rumor = json!({
        "id": "rust-shared-channel-rumor",
        "pubkey": "aa".repeat(32), "created_at": 1700000000,
        "kind": 10445, "tags": [],
        "content": "Rust shared channel interop — encrypted content"
    });
    let event = channel.create_event(&rumor.to_string())?;
    event.verify()?;
    let vectors = Vectors {
        description: "SharedChannel vectors generated by Rust production API".into(),
        secret_hex: hex::encode(secret),
        channel_pubkey: channel.public_key().to_hex(),
        encrypted_event: serde_json::from_str(&event.as_json()).unwrap(),
        plaintext_rumor: rumor,
        group_tagged_event: json!({
            "id": "group-msg-id", "pubkey": "aa".repeat(32),
            "created_at": 1700000000, "kind": 14,
            "tags": [["l", "test-group-id"], ["ms", "1700000000000"]],
            "content": "Hello from Rust group!"
        }),
    };
    fs::create_dir_all(directory()).unwrap();
    let output = directory().join("rust-shared-channel-vectors.json");
    fs::write(&output, serde_json::to_vec_pretty(&vectors).unwrap()).unwrap();
    println!("Generated Rust SharedChannel vectors at {output:?}");
    Ok(())
}

#[test]
fn decrypt_typescript_shared_channel_vector() -> Result<()> {
    let input = directory().join("ts-shared-channel-vectors.json");
    if !input.exists() {
        assert_ne!(
            std::env::var("REQUIRE_INTEROP_VECTORS").as_deref(),
            Ok("true")
        );
        println!("TypeScript SharedChannel vector absent; use the interop generation lane");
        return Ok(());
    }
    let vectors: Vectors = serde_json::from_slice(&fs::read(input).unwrap()).unwrap();
    let secret: [u8; 32] = hex::decode(vectors.secret_hex).unwrap().try_into().unwrap();
    let channel = SharedChannel::new(&secret)?;
    assert_eq!(channel.public_key().to_hex(), vectors.channel_pubkey);
    let event: nostr::Event = serde_json::from_value(vectors.encrypted_event).unwrap();
    event.verify()?;
    assert!(channel.is_channel_event(&event));
    let decrypted: Value = serde_json::from_str(&channel.decrypt_event(&event)?).unwrap();
    assert_eq!(decrypted, vectors.plaintext_rumor);
    let mut altered = event;
    altered.content.push('A');
    assert!(channel.decrypt_event(&altered).is_err());
    Ok(())
}
